"""Private TinyUSB 0.18 copies: runtime EP0 packet size for A/B=8, C=64.

Never edits pico-sdk. The transfer buffer stays 64 bytes. Only packet boundaries
and the first device-descriptor request use descriptor byte 7 at runtime.
"""
from pathlib import Path
import hashlib
import json
HERE=Path(__file__).resolve().parent
import os
src=Path(os.environ['PICO_SDK_PATH'])/'lib'/'tinyusb'/'src'
dest=HERE/'firmware_source/tinyusb_runtime'
dest.mkdir(exist_ok=True)
manifest={}
for name,relative in (('usbd.c','device/usbd.c'),('usbd_control.c','device/usbd_control.c'),('hid_device.c','class/hid/hid_device.c')):
    original=(src/relative).read_text()
    data=original
    def replace_once(old,new):
        global data
        assert data.count(old)==1,(name,old)
        data=data.replace(old,new)
    if name=='usbd.c':
        assert data.count('CFG_TUD_ENDPOINT0_SIZE')==3
        data=data.replace('CFG_TUD_ENDPOINT0_SIZE','tud_descriptor_device_cb()[7]')
        replace_once('case DCD_EVENT_BUS_RESET:\n        TU_LOG_USBD', 'case DCD_EVENT_BUS_RESET:\n        modec_usb_reset();\n        TU_LOG_USBD')
        replace_once('_usbd_queued_setup--;','_usbd_queued_setup--;\n        modec_usb_setup(&event.setup_received);')
        replace_once('if (_usbd_queued_setup) {','if (_usbd_queued_setup) {\n          modec_usb_flags(DS3_T_SKIPPED);')
        replace_once('if (!process_control_request(event.rhport, &event.setup_received)) {','if (!process_control_request(event.rhport, &event.setup_received)) {\n          modec_usb_flags(DS3_T_STALL);')
    elif name=='usbd_control.c':
        needle='_ctrl_xfer.total_xferred, CFG_TUD_ENDPOINT0_SIZE)'
        assert data.count(needle)==1
        data=data.replace(needle,'_ctrl_xfer.total_xferred, tud_descriptor_device_cb()[7])')
        needle='xferred_bytes < CFG_TUD_ENDPOINT0_SIZE'
        assert data.count(needle)==1
        data=data.replace(needle,'xferred_bytes < tud_descriptor_device_cb()[7]')
        replace_once('dcd_edpt0_status_complete(rhport, &_ctrl_xfer.request);','dcd_edpt0_status_complete(rhport, &_ctrl_xfer.request);\n    modec_usb_flags(result == XFER_RESULT_SUCCESS ? DS3_T_ACK : DS3_T_ERROR);')
        replace_once('  if (_ctrl_xfer.request.bmRequestType_bit.direction == TUSB_DIR_OUT) {\n    TU_VERIFY',
          '  if (result == XFER_RESULT_SUCCESS) modec_usb_data(_ctrl_epbuf.buf, (uint16_t)xferred_bytes, _ctrl_xfer.total_xferred);\n  else modec_usb_flags(DS3_T_ERROR);\n\n  if (_ctrl_xfer.request.bmRequestType_bit.direction == TUSB_DIR_OUT) {\n    TU_VERIFY')
        replace_once('      // Stall both IN and OUT control endpoint','      modec_usb_flags(DS3_T_STALL);\n      // Stall both IN and OUT control endpoint')
    else:
        replace_once('#include "hid_device.h"','#include "class/hid/hid_device.h"')
        replace_once('bool hidd_control_xfer_cb(uint8_t rhport, uint8_t stage, tusb_control_request_t const *request) {',
          'bool hidd_control_xfer_cb(uint8_t rhport, uint8_t stage, tusb_control_request_t const *request) {\n  if (modec_hid_feature_request(request)) return modec_hid_feature_control(rhport, stage, request);')
    replace_once('#include "tusb_option.h"','#include "tusb_option.h"\n#include "usb_trace.h"')
    data='// Private EP0/DS3 wire-feature/trace hooks; generated by prepare_usb_runtime.py.\n'+data
    if not (dest/name).exists() or (dest/name).read_text()!=data:(dest/name).write_text(data)
    manifest[name]={'upstream_sha256':hashlib.sha256(original.encode()).hexdigest(),
                    'patched_sha256':hashlib.sha256(data.encode()).hexdigest()}
(dest/'provenance.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('SUMMARY private TinyUSB EP0/DS3 feature/trace copies generated; SDK unchanged')
