"""Generate deterministic C assets, keeping HTTP routes fixed and filesystem-free."""
import pathlib
root=pathlib.Path(__file__).resolve().parents[1]
(root/'net').mkdir(exist_ok=True)
out=['/* Generated by tools/embed_web.py from web/. */', '#ifndef BUZZ_WEB_ASSETS_H', '#define BUZZ_WEB_ASSETS_H']
for name,symbol in [('index.html','index'),('style.css','style'),('app.js','app')]:
 data=(root/'web'/name).read_bytes()
 out.append('static const unsigned char web_'+symbol+'[] = {')
 for i in range(0,len(data),20): out.append(' '+','.join(str(b) for b in data[i:i+20])+',')
 out.append('};')
out.append('#endif')
(root/'net'/'web_assets.h').write_text('\n'.join(out)+'\n',encoding='ascii')
